    public void cargarClientesEnTabla(List<Cliente> lista) {
        DefaultTableModel modelo = (DefaultTableModel) txtTabla.getModel();
        modelo.setRowCount(0); 

        for (Cliente c : lista) {
            Object[] fila = {c.getCedula(),c.getNombre(),c.calcularEdad(), c.getTelefono(),c.getCorreo(),c.getLicenciaConducir()
            };
            modelo.addRow(fila);
        }
    }

private void inicializarClientes() {
   cargarClientesEnTabla(Cliente.getClientes());
        txtBuscar.setText(placeholderText);
        txtBuscar.getDocument().addDocumentListener(new DocumentListener() {
            
            @Override
            public void changedUpdate(DocumentEvent e) {
                buscarClientes();
            }
            @Override
            public void removeUpdate(DocumentEvent e) {
                buscarClientes();
            }
            @Override
            public void insertUpdate(DocumentEvent e) {
                buscarClientes();
            }
            
private void buscarClientes() {
      String texto = txtBuscar.getText().toLowerCase();
        if (texto.equals(placeholderText.toLowerCase()) || texto.trim().isEmpty()) {
        cargarClientesEnTabla(Cliente.getClientes());
        return;
  }
                
    List<Cliente> todos = Cliente.getClientes();
    List<Cliente> filtrados = new ArrayList<>();
                
     for (Cliente c : todos) {
      if (c.getCedula().toLowerCase().contains(texto) ||
         c.getNombre().toLowerCase().contains(texto) ||
           c.getCorreo().toLowerCase().contains(texto) ||
            c.getTelefono().toLowerCase().contains(texto) ||
           c.getLicenciaConducir().toLowerCase().contains(texto)) {
         filtrados.add(c);
        }
  }
  cargarClientesEnTabla(filtrados);
 }
});
     txtTabla.getSelectionModel().addListSelectionListener(e -> {
       if (!e.getValueIsAdjusting() && txtTabla.getSelectedRow() != -1) {
           int fila = txtTabla.getSelectedRow();
       String cedula = txtTabla.getValueAt(fila, 0).toString();
           String nombre = txtTabla.getValueAt(fila, 1).toString();
          jTextField1.setText("Seleccionado: " + nombre + " (" + cedula + ")");
            }
        });
    }


    public void ActualizarTablaClientes() {
        cargarClientesEnTabla(Cliente.getClientes());
    }
    
