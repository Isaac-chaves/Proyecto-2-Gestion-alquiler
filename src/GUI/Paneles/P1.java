    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
int filaSeleccionada = txtTabla.getSelectedRow();
if (filaSeleccionada != -1) {
    String cedula = txtTabla.getValueAt(filaSeleccionada, 0).toString(); 
    Cliente c = Cliente.buscarClientePorCedula(cedula);
    
    if (c != null) {
        P1_Actualizar dialogoActualizar = new P1_Actualizar(null, true, c);
        dialogoActualizar.setVisible(true);
        
        // Actualizar la tabla después de cerrar el diálogo
        // Usar SwingUtilities.invokeLater para asegurar que se ejecute después
        javax.swing.SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                ActualizarTablaClientes();
            }
        });
    } else {
        JOptionPane.showMessageDialog(this, "No se encontró el cliente seleccionado");
    }
} else {
    JOptionPane.showMessageDialog(this, "Seleccione una fila para actualizar");
}
    }//GEN-LAST:event_jButton3ActionPerformed

