    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
   int filaSeleccionada = txtTabla.getSelectedRow();
     if (filaSeleccionada != -1) {
       String cedula = txtTabla.getValueAt(filaSeleccionada, 0).toString();
         String nombre = txtTabla.getValueAt(filaSeleccionada, 1).toString();
            
       int respuesta = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de que desea eliminar al cliente " + nombre + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION,
             JOptionPane.QUESTION_MESSAGE);
                
      if (respuesta == JOptionPane.YES_OPTION) {
          try {
       boolean eliminado = Cliente.eliminarCliente(cedula);
                    
         if (eliminado) {
           cargarClientesEnTabla(Cliente.getClientes());
          jTextField1.setText("seleccionado:");
             JOptionPane.showMessageDialog(this,
        "Cliente eliminado correctamente",
               "Éxito",
             JOptionPane.INFORMATION_MESSAGE);
          } else {
        JOptionPane.showMessageDialog(this,
          "No se pudo eliminar el cliente",
               "Error",
               JOptionPane.ERROR_MESSAGE);
                    }
 } catch (Exception e) {
         DefaultTableModel modelo = (DefaultTableModel) txtTabla.getModel();
      modelo.removeRow(filaSeleccionada);
        jTextField1.setText("seleccionado:");
        JOptionPane.showMessageDialog(this,
        "Cliente eliminado de la tabla correctamente",
         "Éxito",
         JOptionPane.INFORMATION_MESSAGE);
                }
 }
        } else {
            JOptionPane.showMessageDialog(this,
                "Seleccione un cliente para eliminar",
                "Aviso",
                JOptionPane.WARNING_MESSAGE);
        }       
    }//GEN-LAST:event_jButton4ActionPerformed

