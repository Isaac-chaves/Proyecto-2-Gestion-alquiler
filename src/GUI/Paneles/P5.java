    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed

    int fila = TablareservaEspera.getSelectedRow();
    if (fila != -1) {
        String id = TablareservaEspera.getValueAt(fila, 0).toString();
        int r = javax.swing.JOptionPane.showConfirmDialog(this, "¿Cancelar reserva en espera?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
        if (r == javax.swing.JOptionPane.YES_OPTION) {
            if (ReservaMetodos.cancelarReservaEnEspera(id)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cancelada.");
                cargarTablas();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al cancelar.");
            }
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una reserva en espera.");
    }
    }//GEN-LAST:event_jButton5ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
  
         int fila = Tablareserva.getSelectedRow();
    
    if (fila != -1) {
        String id = Tablareserva.getValueAt(fila, 0).toString();

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de cancelar esta reserva?",
            "Confirmar cancelación",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            boolean cancelado = ReservaMetodos.cancelar(id);
            if (cancelado) {
                javax.swing.JOptionPane.showMessageDialog(this, "Reserva cancelada con éxito.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo cancelar. La reserva ya inició o no existe.");
            }
            cargarTablas(); // Actualizar tabla después de cancelar
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una reserva para cancelar.");
    }
        
    }//GEN-LAST:event_jButton3ActionPerformed

