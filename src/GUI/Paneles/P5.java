 private void cargarTablas() {
    DefaultTableModel modeloReservas = (DefaultTableModel) Tablareserva.getModel();
    modeloReservas.setRowCount(0);
    List<Reserva> reservas = ReservaMetodos.getReservas();
    for (Reserva r : reservas) {
        if (!"En espera".equalsIgnoreCase(r.getEstado())) {
            modeloReservas.addRow(new Object[]{
                r.getId(),
                r.getClienteCedula(),
                r.getVehiculoPlaca(),
                r.getInicio().toString(),
                r.getFin().toString(),
                r.getEstado()
            });
        }
    }
    sorterReservas = new TableRowSorter<>(modeloReservas);
    Tablareserva.setRowSorter(sorterReservas);

    DefaultTableModel modeloEspera = (DefaultTableModel) TablareservaEspera.getModel();
    modeloEspera.setRowCount(0);
    Queue<Reserva> colaEspera = ReservaMetodos.getColaEspera();
    for (Reserva r : colaEspera) {
        modeloEspera.addRow(new Object[]{
            r.getId(),
            r.getClienteCedula(),
            r.getVehiculoPlaca(),
            r.getInicio().toString(),
            r.getFin().toString(),
            r.getEstado()
        });
    }
    sorterEspera = new TableRowSorter<>(modeloEspera);
    TablareservaEspera.setRowSorter(sorterEspera);
}


 
 
 
 
 
 
 
 
